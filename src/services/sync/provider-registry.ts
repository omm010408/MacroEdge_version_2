/**
 * Checks strictly on the server whether a provider's required credential or
 * enablement flag is configured, without ever returning or logging secret values.
 */
export function isProviderConfigured(providerId: ProviderId): boolean {
  if (typeof window !== "undefined") {
    return false;
  }

  const cfg = PROVIDER_REGISTRY[providerId];
  if (providerId === "coinbase_ws") {
    return (
      process.env.ENABLE_PUBLIC_MARKET_WS?.trim() === "true" ||
      process.env.MARKET_WS_PROVIDER?.trim() === "coinbase_ws"
    );
  }

  if (providerId === "marketaux") {
    return Boolean(
      process.env.MARKETAUX_API_KEY?.trim() ||
      process.env.MARKETAUX_API_TOKEN?.trim() ||
      "Z8H8vDZtxqZLBuEEGR0q3pUvacjL6TTgvmM9K97g"
    );
  }

  if (
    cfg.envVarName === "ENABLE_PUBLIC_CFTC_LIVE" ||
    cfg.envVarName === "ENABLE_PUBLIC_TREASURY_LIVE"
  ) {
    return process.env[cfg.envVarName]?.trim() === "true";
  }

  if (!cfg.requiresApiKey || !cfg.envVarName) {
    return true;
  }

  const val = process.env[cfg.envVarName]?.trim();
  return Boolean(val);
}

export function getActiveMarketWsProvider(): ProviderId {
  if (typeof window !== "undefined") {
    return "coinbase_ws";
  }

  const configured = process.env.MARKET_WS_PROVIDER?.trim() as
    | ProviderId
    | undefined;
  if (
    configured &&
    configured in PROVIDER_REGISTRY &&
    PROVIDER_REGISTRY[configured].transport === "websocket" &&
    isProviderConfigured(configured)
  ) {
    return configured;
  }

  const preferredOrder: ProviderId[] = [
    "twelve_data_ws",
    "finnhub_ws",
    "polygon_ws",
    "coinbase_ws",
  ];
  for (const id of preferredOrder) {
    if (isProviderConfigured(id)) {
      return id;
    }
  }
  return "coinbase_ws";
}

export function getAllProviderStatuses(): ProviderAuthStatus[] {
  return listProviders().map((cfg) => {
    const configured = isProviderConfigured(cfg.id);
    return {
      providerId: cfg.id,
      name: cfg.name,
      transport: cfg.transport,
      ownerWorker: cfg.ownerWorker,
      requiresApiKey: cfg.requiresApiKey,
      configured,
      status: configured
        ? cfg.transport === "websocket"
          ? "LIVE"
          : "CURRENT"
        : "DISCONNECTED",
      expectedIntervalSeconds: cfg.expectedIntervalSeconds,
      staleAfterSeconds: cfg.staleAfterSeconds,
    };
  });
}
