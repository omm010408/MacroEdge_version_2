function makeUnconfiguredMeta(
  source: string,
  seriesId: string,
  frequency: DatasetMeta["frequency"],
  units: string
): DatasetMeta {
  return {
    source,
    seriesId,
    observationDate: "—",
    lastUpdated: "",
    frequency,
    units,
    mode: "UNCONFIGURED",
  };
}

